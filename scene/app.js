/* ============================================================
   Numidea Labs — project sheets.
   The page is complete static HTML (generated by scripts/build-scene.mjs).
   Language is handled by ../assets/page-i18n.js (shared with legal/);
   this file opens captures in a viewer, hands the offer's request to the
   home page's form, opens WhatsApp in the page's language and shows the
   phone bar.
   ============================================================ */
(function () {
  var root = document.documentElement;
  var DICT = {};
  try { DICT = JSON.parse(document.getElementById('i18n').textContent) || {}; } catch (e) {}
  function t(k) { var d = DICT[root.lang] || DICT.fr || {}; return d[k] != null ? d[k] : (DICT.fr || {})[k]; }

  /* image viewer: progressive — without JS (or <dialog>) the link opens the
     file. The image goes in the pane: fitted to the screen on a desk, at
     its own size on a phone, where the pane scrolls (style.css). */
  var dlg = document.getElementById('viewer');
  var pane = dlg && dlg.querySelector('.viewer-pane');
  if (dlg && pane && typeof dlg.showModal === 'function') {
    // created on first open: an <img> with no src counts as a broken image
    var big = null;
    document.addEventListener('click', function (ev) {
      var a = ev.target.closest && ev.target.closest('a.zoom');
      if (!a || ev.metaKey || ev.ctrlKey || ev.shiftKey) return;
      ev.preventDefault();
      var img = a.querySelector('img');
      if (!big) { big = document.createElement('img'); pane.appendChild(big); }
      big.src = a.getAttribute('href');
      big.alt = img ? img.alt : '';
      dlg.classList.toggle('is-tall', !!(img && img.naturalHeight > img.naturalWidth));
      dlg.showModal();
      pane.scrollTop = 0; pane.scrollLeft = 0;
    });
    // a click on the backdrop closes it, and on a desk a click on the
    // fitted image too; on a phone the image is panned, not a way out
    var pan = window.matchMedia('(max-width: 699px)');
    dlg.addEventListener('click', function (ev) { if (ev.target === dlg || (ev.target === big && !pan.matches)) dlg.close(); });
    dlg.addEventListener('close', function () { if (big) big.removeAttribute('src'); });
  }

  /* The offer's request (data-prefill) lands on the home page's form
     already written: its own Aperçu request (prev.msg) without its first
     line, under the greeting the home page puts above a carried scope
     (price.estHello). It travels as the price guide's scope does
     (sessionStorage 'numidea-prefill', one tab, one visit), and the home
     page reads it and clears it (assets/app.js). */
  document.addEventListener('click', function (ev) {
    var a = ev.target.closest && ev.target.closest('a[data-prefill]');
    var msg = a && t('prev.msg');
    if (!msg) return;
    try { sessionStorage.setItem('numidea-prefill', msg.split('\n').slice(1).join('\n')); } catch (e) {}
  }, true);

  /* WhatsApp opens on the home page's line in the page's language (the
     markup carries the French), with the ad's ?ref= tag as the home page
     adds it; set as the link is followed, so a language switch needs no
     rewrite. */
  function waHref(a) {
    var text = t(a.getAttribute('data-wa-text'));
    if (!text) return;
    var r = ''; try { r = (new URLSearchParams(location.search).get('ref') || '').replace(/[^\w-]/g, '').slice(0, 20); } catch (e) {}
    a.href = a.href.split('?')[0] + '?text=' + encodeURIComponent(text + (r ? ' [' + r + ']' : ''));
  }
  ['click', 'auxclick', 'contextmenu'].forEach(function (type) {
    document.addEventListener(type, function (ev) {
      var a = ev.target.closest && ev.target.closest('a.wa-link[data-wa-text]');
      if (a) waHref(a);
    }, true);
  });

  /* The phone bar (style.css shows it under 721px, not on a phone on its
     side): on once the intro is behind the visitor, off while the page's
     foot is on screen (it offers the same two ways in). */
  var bar = document.querySelector('.m-contact');
  var intro = document.querySelector('.intro'), foot = document.querySelector('.outro');
  if (bar && intro && foot && 'IntersectionObserver' in window) {
    var past = false, footIn = false;
    var update = function () { bar.classList.toggle('on', past && !footIn); };
    new IntersectionObserver(function (es) {
      es.forEach(function (e) { past = !e.isIntersecting && e.boundingClientRect.top < 0; });
      update();
    }).observe(intro);
    new IntersectionObserver(function (es) {
      es.forEach(function (e) { footIn = e.isIntersecting; });
      update();
    }).observe(foot);
  }
})();
