/**
 * The Content-Security-Policy the hosts send as a response header —
 * `headerPolicy(kind)`, written into vercel.json and netlify.toml by
 * `applyHeaders()` (build-csp.mjs and bump.mjs call it after the metas).
 *
 * Each page already carries its own exact policy in a meta (csp.mjs). The
 * browser enforces every policy it is given, meta and header alike, and a
 * resource loads only when ALL of them allow it. So the header may never be
 * tighter than a page's meta, or it blocks what the meta allows (a stale
 * hash here would kill a page's boot script on the live site). It is the
 * union of the metas of its kind: every directive, every source, every
 * inline-script hash of every page of that kind. The meta stays the tight,
 * per-page rule; the header adds what a meta cannot carry:
 *
 *   frame-ancestors 'self'       no other site may frame a page
 *   upgrade-insecure-requests    an http:// subresource is fetched over https
 *   report-uri                   violations are POSTed to /api/csp-report
 *                                (api/csp-report.js logs them in Vercel's
 *                                runtime logs). A meta cannot report.
 *
 * Why the header at all, when the meta already blocks: reporting (a meta
 * policy sends no report, so an injected script or a new third-party host
 * is blocked silently), frame-ancestors, and scanners (Observatory and
 * securityheaders.com read the header only).
 *
 * Two kinds, as in csp.mjs: 'page' (every PAGES file) and 'embed'
 * (workspacehq/embed/*.html, which need 'unsafe-eval' and data: fonts).
 * Vercel sends them on exclusive paths ("/:path((?!workspacehq/embed/).*)"
 * and "/workspacehq/embed/(.*)"), so no page ever gets 'unsafe-eval' from
 * the header. Netlify cannot exclude a path and joins two matching values of
 * one header with a comma (the browser then enforces both, and the embeds
 * lose eval), so the Netlify mirror sends one policy, 'any': the union of
 * both kinds. Its metas still hold each page to its own rule.
 *
 * A page whose inline script changes gets a new hash, so the header changes
 * with it: `npm run build` (or `npm run csp`, or bump) rewrites both files,
 * and check.mjs 16 fails the build (Vercel's included) while either is stale.
 * A merge conflict in either file's policy line resolves with `npm run csp`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, PAGES, EXTRA_PAGES } from '../site.mjs';
import { cspKind, cspOf } from './csp.mjs';
import { parsePolicy } from './csp-floor.mjs';

export const REPORT_PATH = '/api/csp-report';
// report-uri only, on purpose: every browser still sends it, and a test in Chromium posted the report. report-to
// (with a Reporting-Endpoints header) posted nothing in headless Chromium in a minute and more, and Chrome ignores
// report-uri as soon as report-to is there, so adding it unproven could silence Chrome's reports. Add it once a real
// Chrome is seen delivering it on a preview.
export const HEADER_ONLY = [['frame-ancestors', "'self'"], ['upgrade-insecure-requests'], ['report-uri', REPORT_PATH]];

export const VERCEL_SOURCE = { page: '/:path((?!workspacehq/embed/).*)', embed: '/workspacehq/embed/(.*)' };
export const NETLIFY_MARK = ['# >>> generated by npm run csp (scripts/lib/csp-header.mjs): do not edit by hand', '# <<< generated'];

/** The union, directive by directive, of the given policies (first seen order; hashes sorted, so a reorder is no diff). */
export function unionPolicy(policies) {
  const out = new Map();
  for (const p of policies) for (const { name, values } of parsePolicy(p)) {
    if (!out.has(name)) out.set(name, []);
    const list = out.get(name);
    for (const v of values) if (!list.includes(v)) list.push(v);
  }
  return [...out].map(([name, values]) => {
    const plain = values.filter((v) => !/^'sha256-/.test(v)), hashes = values.filter((v) => /^'sha256-/.test(v)).sort();
    // 'none' plus a source means the source: keep 'none' only when alone
    const vals = [...plain, ...hashes];
    return [name, vals.length > 1 ? vals.filter((v) => v !== "'none'") : vals];
  });
}

const read = (f) => readFileSync(join(ROOT, f), 'utf8');
const SITE_FILES = () => [...PAGES, ...EXTRA_PAGES].filter((f) => existsSync(join(ROOT, f)));

/** Every page's meta policy, by kind: { page: [...], embed: [...] } (read from disk, as built). */
export function metaPolicies(files = SITE_FILES()) {
  const by = { page: [], embed: [] };
  for (const f of files) { const p = cspOf(read(f)); if (p != null) by[cspKind(f)].push({ file: f, policy: p }); }
  return by;
}

/** The header policy for 'page', 'embed' or 'any' (Netlify: both). */
export function headerPolicy(kind, metas = metaPolicies()) {
  const list = kind === 'any' ? [...metas.page, ...metas.embed] : metas[kind];
  if (!list || !list.length) throw new Error(`no page of kind "${kind}" carries a CSP meta: build the pages first`);
  return [...unionPolicy(list.map((m) => m.policy)).map(([n, v]) => [n, ...v]), ...HEADER_ONLY].map((d) => d.join(' ')).join('; ');
}

/* vercel.json with the two CSP rules set; every other rule untouched */
export function vercelWith(json, metas = metaPolicies()) {
  const cfg = JSON.parse(json);
  // this file's own rules: a CSP-only rule on one of the two sources (the embeds' Cache-Control rule shares a source and stays)
  const own = (r) => Object.values(VERCEL_SOURCE).includes(r.source) && (r.headers || []).every((h) => h.key === 'Content-Security-Policy');
  const rules = (cfg.headers || []).filter((r) => !own(r));
  for (const r of rules) if (r.source === '/(.*)') r.headers = r.headers.filter((h) => h.key !== 'Content-Security-Policy');
  for (const kind of ['page', 'embed']) {
    rules.push({ source: VERCEL_SOURCE[kind], headers: [{ key: 'Content-Security-Policy', value: headerPolicy(kind, metas) }] });
  }
  cfg.headers = rules;
  return JSON.stringify(cfg, null, 2) + '\n';
}

/* netlify.toml with its generated block (the "/*" CSP line) rewritten */
export function netlifyWith(toml, metas = metaPolicies()) {
  const [open, close] = NETLIFY_MARK;
  const a = toml.indexOf(open), b = toml.indexOf(close);
  if (a < 0 || b < a) throw new Error(`netlify.toml has no generated block (${open} … ${close})`);
  const line = `    Content-Security-Policy = ${JSON.stringify(headerPolicy('any', metas))}\n`;
  return toml.slice(0, a) + open + '\n' + line + toml.slice(b);
}

/** Writes (or, with write = false, only compares) both hosts' header policies. Returns the files that differed. */
export function applyHeaders({ write = true } = {}) {
  const metas = metaPolicies(), stale = [];
  for (const [file, fn] of [['vercel.json', vercelWith], ['netlify.toml', netlifyWith]]) {
    const have = read(file), want = fn(have, metas);
    if (want !== have) { stale.push(file); if (write) writeFileSync(join(ROOT, file), want); }
  }
  return stale;
}
